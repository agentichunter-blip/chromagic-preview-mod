"""Scale the banner numerals 3x with exact pixels for the loading percentage."""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[1]
font = root / 'components/osd/system/banner_font.c'
source = font.read_text().split('static const uint8_t Bits[]={', 1)[1].split('};', 1)[0]
bits = bytes(int(x, 16) for x in re.findall(r'0x[0-9a-f]+', source))
percent = bytes([0xc3, 0xc6, 0x0c, 0x18, 0x30, 0x63, 0xc3, 0])
glyphs = [percent] + [bits[(ord(c)-32)*8:(ord(c)-31)*8] for c in '0123456789']
# Keep zero's counter open at the larger size so it cannot read as an eight.
glyphs[1] = bytes([0x7e, 0xff, 0xe7, 0xe7, 0xe7, 0xe7, 0xff, 0x7e])
bitmap = bytearray()
for glyph in glyphs:
    for row in glyph:
        expanded = int(''.join(('1' if row & (1 << x) else '0') * 3 for x in range(7, -1, -1)), 2).to_bytes(3, 'big')
        bitmap.extend(expanded * 3)
lines = ['/* Generated by tools/generate_progress_font.py; 3x banner digits. */', '#include "lvgl.h"', 'static const uint8_t Bits[] = {']
lines += ['    ' + ','.join(f'0x{x:02x}' for x in bitmap[i:i+18]) + ',' for i in range(0, len(bitmap), 18)]
lines += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t Glyphs[] = {{0},']
lines += [f'    {{.bitmap_index={i*72},.adv_w=432,.box_w=24,.box_h=24,.ofs_x=0,.ofs_y=0}},' for i in range(11)]
lines += ['};', '''static const lv_font_fmt_txt_cmap_t Map[] = {
    {.range_start=37,.range_length=1,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},
    {.range_start=48,.range_length=10,.glyph_id_start=2,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}
};
static lv_font_fmt_txt_glyph_cache_t Cache;
static const lv_font_fmt_txt_dsc_t Desc = {.glyph_bitmap=Bits,.glyph_dsc=Glyphs,.cmaps=Map,.cmap_num=2,.bpp=1,.cache=&Cache};
const lv_font_t chromatic_progress = {
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height=24,.base_line=0,.subpx=LV_FONT_SUBPX_NONE,.dsc=&Desc
};''']
(root / 'components/osd/system/progress_font.c').write_text('\n'.join(lines) + '\n')
