"""Regenerate native RGB565 logo cards (requires cairosvg and Pillow)."""
from pathlib import Path
from io import BytesIO
import cairosvg
from PIL import Image
HERE = Path(__file__).resolve().parent
out = ['/* Generated by mcu/tools/platform-logos/generate.py; see its README. */', '#pragma once']
for stem, name in [('gb', 'PlatformGB'), ('gbc', 'PlatformGBC')]:
    # A bright neutral card preserves the original wordmark colors at native resolution.
    png = cairosvg.svg2png(url=str(HERE / (stem + '.svg')), output_width=60 * 4)
    logo = Image.open(BytesIO(png)).convert('RGBA')
    logo = logo.resize((60, round(logo.height / 4)), Image.Resampling.LANCZOS)
    card = Image.new('RGB', (60, 68), '#e8e8e0')
    card.paste(logo, (0, (68-logo.height)//2), logo)
    pixels=[]
    for r,g,b in card.getdata():
        value=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
        pixels.extend((value&255,value>>8))
    out.append('static const uint8_t '+name+'Pixels[] = {')
    out.extend('    '+','.join('0x%02x'%v for v in pixels[i:i+24])+',' for i in range(0,len(pixels),24))
    out.extend(['};', 'static const lv_img_dsc_t '+name+' = {', '    .header = {.cf=LV_IMG_CF_TRUE_COLOR, .w=60, .h=68},', '    .data_size=sizeof('+name+'Pixels), .data='+name+'Pixels,', '};'])
(HERE.parent.parent / 'components/osd/system/platform_logos.h').write_text('\n'.join(out)+'\n')
